"""Repository grounding — retrieve relevant repo content for each question.

Two retrieval sources, both cheap and serverless-friendly:

1. **MkDocs search index** (``search_index.json``) — built from the full
   docs site (docs/, tutorials/, poc-agenda/). Fetched once per instance
   from the published site and cached in memory.

2. **Code manifest** (``code_manifest.json``) — generated by
   ``build_code_manifest.py`` at deploy time; indexes notebooks, data
   generators, and Bicep modules with titles/summaries/keywords.

Both use the same lightweight term-scoring ranker (no embeddings, no
external service) so the Function stays on the Consumption plan with no
extra Azure resources. Retrieved chunks are injected into the system
context so Mode 1 answers cite *actual* repo content instead of the
model's parametric memory.

Failure model: if either source is unavailable, retrieval returns an
empty list and the Copilot answers as before (system prompt + optional
MS Learn fallback). Grounding is additive, never blocking.
"""

from __future__ import annotations

import json
import logging
import os
import re
import threading
import time
from pathlib import Path

import httpx

# ── Configuration ───────────────────────────────────────────────
DOCS_SITE_URL = os.environ.get(
    "DOCS_SITE_URL",
    "https://fgarofalo56.github.io/Suppercharge_Microsoft_Fabric",
).rstrip("/")
SEARCH_INDEX_URL = f"{DOCS_SITE_URL}/search/search_index.json"
MANIFEST_PATH = Path(__file__).resolve().parent / "code_manifest.json"

HTTP_TIMEOUT = 20.0
INDEX_TTL_SECONDS = 6 * 60 * 60  # re-fetch the search index every 6h
MAX_CHUNKS_PER_SOURCE = 4
MAX_CHUNK_CHARS = 700
MAX_CONTEXT_CHARS = 6000

# ── In-memory caches (per instance; cold-start safe) ────────────
_index_cache: dict = {"data": None, "fetched_at": 0.0}
_manifest_cache: dict = {"data": None}
_lock = threading.Lock()


# ── Loading ─────────────────────────────────────────────────────
def _load_search_index() -> list[dict]:
    """Fetch + cache the MkDocs search index. Returns [] on failure."""
    now = time.time()
    with _lock:
        if (
            _index_cache["data"] is not None
            and (now - _index_cache["fetched_at"]) < INDEX_TTL_SECONDS
        ):
            return _index_cache["data"]

    try:
        with httpx.Client(timeout=HTTP_TIMEOUT) as client:
            r = client.get(SEARCH_INDEX_URL)
        if r.status_code != 200:
            logging.warning("repo_grounding: search index HTTP %s", r.status_code)
            return _index_cache["data"] or []
        data = r.json()
        docs = data.get("docs", []) if isinstance(data, dict) else []
        with _lock:
            _index_cache["data"] = docs
            _index_cache["fetched_at"] = now
        logging.info("repo_grounding: loaded search index (%d docs)", len(docs))
        return docs
    except Exception as e:
        logging.warning("repo_grounding: search index fetch failed: %s", e)
        return _index_cache["data"] or []


def _load_manifest() -> list[dict]:
    """Load the bundled code manifest. Returns [] if missing."""
    with _lock:
        if _manifest_cache["data"] is not None:
            return _manifest_cache["data"]
    try:
        raw = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        entries = raw.get("entries", []) if isinstance(raw, dict) else []
    except Exception as e:
        logging.warning("repo_grounding: manifest load failed: %s", e)
        entries = []
    with _lock:
        _manifest_cache["data"] = entries
    logging.info("repo_grounding: loaded code manifest (%d entries)", len(entries))
    return entries


# ── Ranking ─────────────────────────────────────────────────────
