def _terms(query: str) -> list[str]:
    return [t for t in _WORD_RE.findall(query.lower()) if t not in _STOP]


def _score(
    terms: list[str], title: str, text: str, extra: list[str] | None = None
) -> float:
    title_l = title.lower()
    text_l = text.lower()
    extra_l = " ".join(extra or []).lower()
    score = 0.0
    for term in terms:
        if term in title_l:
            score += 10.0
        if re.search(rf"\b{re.escape(term)}\b", title_l):
            score += 5.0
        if term in extra_l:
            score += 4.0
        # Cap body hits so long docs don't dominate
        score += min(text_l.count(term), 5)
    return score


_TAG_RE = re.compile(r"<[^>]+>")


def _strip_html(text: str) -> str:
    """MkDocs index text contains raw HTML — strip tags, collapse whitespace."""
    return re.sub(r"\s{2,}", " ", _TAG_RE.sub(" ", text)).strip()


def _snippet(text: str, terms: list[str], width: int = MAX_CHUNK_CHARS) -> str:
    clean = _strip_html(text)
    clean_l = clean.lower()
    best = -1
    for t in terms:
        idx = clean_l.find(t)
        if idx != -1 and (best == -1 or idx < best):
            best = idx
    if best == -1:
        return clean[:width].strip()
    start = max(0, best - 120)
    end = min(len(clean), best + width - 120)
    prefix = "…" if start > 0 else ""
    suffix = "…" if end < len(clean) else ""
    return prefix + clean[start:end].strip() + suffix


# ── Public API ──────────────────────────────────────────────────
def retrieve(query: str, max_chunks: int = MAX_CHUNKS_PER_SOURCE) -> list[dict]:
    """Return up to ``max_chunks`` grounding chunks for ``query``.

    Each chunk: {"source": "docs"|"code", "title", "location"|"path",
                 "url", "text", "score"}. Sorted by score desc.
    Never raises — returns [] when nothing matches or sources unavailable.
    """
    terms = _terms(query)
    if not terms:
        return []

    chunks: list[dict] = []

    # ── Docs (MkDocs search index) ──────────────────────────────
    for doc in _load_search_index():
        title = doc.get("title") or ""
        text = doc.get("text") or ""
        location = doc.get("location") or ""
        if not location or not text:
            continue
        s = _score(terms, title, text)
        if s > 0:
            chunks.append(
                {
                    "source": "docs",
                    "title": title or location,
                    "location": location,
                    "url": f"{DOCS_SITE_URL}/{location}",
                    "text": _snippet(text, terms),
                    "score": s,
                }
            )

    # ── Code manifest (notebooks / generators / bicep) ─────────
    for entry in _load_manifest():
        s = _score(
            terms,
            entry.get("title", ""),
            entry.get("summary", ""),
            extra=[*entry.get("keywords", []), entry.get("path", "")],
        )
        if s > 0:
            chunks.append(
                {
                    "source": "code",
                    "title": f"{entry.get('title', '')} ({entry.get('type', 'code')})",
                    "path": entry.get("path", ""),
                    "url": entry.get("path", ""),
                    "text": entry.get("summary", "")[:MAX_CHUNK_CHARS],
                    "score": s,
                }
            )

    chunks.sort(key=lambda c: c["score"], reverse=True)

    # Dedupe docs hits by page (keep highest-scoring anchor per page)
    seen_pages: set[str] = set()
    deduped: list[dict] = []
    for c in chunks:
        if c["source"] == "docs":
            page = c["location"].split("#")[0]
            if page in seen_pages:
                continue
            seen_pages.add(page)
        deduped.append(c)
        if len(deduped) >= max_chunks * 2:
            break

    # Keep a mix: up to max_chunks docs + up to max_chunks code
    docs_hits = [c for c in deduped if c["source"] == "docs"][:max_chunks]
    code_hits = [c for c in deduped if c["source"] == "code"][:max_chunks]
    return docs_hits + code_hits


def format_grounding_context(chunks: list[dict]) -> str:
    """Render retrieved chunks as a system-message context block.

    Bounded to MAX_CONTEXT_CHARS so the prompt budget stays predictable.
    """
    if not chunks:
        return ""
    lines = [
        "## Retrieved repository content (ground this answer in THESE sources)",
        "Cite these paths/URLs in your answer. If none of these are relevant, say so and fall back to your other modes.",
        "",
    ]
    total = 0
    for i, c in enumerate(chunks, 1):
        if c["source"] == "docs":
            header = f"[{i}] DOCS: {c['title']} — {c['url']}"
        else:
            header = f"[{i}] CODE: {c['title']} — `{c.get('path', '')}`"
        block = f"{header}\n{c['text']}\n"
        if total + len(block) > MAX_CONTEXT_CHARS:
            break
        lines.append(block)
        total += len(block)
    return "\n".join(lines)


