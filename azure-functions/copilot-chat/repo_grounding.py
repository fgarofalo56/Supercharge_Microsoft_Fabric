if __name__ == "__main__":
    import sys

    q = " ".join(sys.argv[1:]) or "bronze NOAA ingestion notebook"
    hits = retrieve(q)

    def _safe(s: str) -> str:
        return s.encode("ascii", errors="replace").decode("ascii")

    print(f"{len(hits)} chunks for {q!r}:\n")
    for h in hits:
        print(_safe(f"  [{h['source']}] {h['title']} (score {h['score']:.1f})"))
        print(_safe(f"    {h.get('url') or h.get('path')}"))
    print("\n--- formatted context ---")
    print(_safe(format_grounding_context(hits)[:1500]))
